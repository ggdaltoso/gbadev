"""Builds a Butano sprite font from the Zelda-like pack's font.png.

Writes snippets/hud/graphics/font.{bmp,json}: 94 glyphs of 8x16, from '!' to '~'
in ASCII order, one below the other. Characters the pack doesn't have are blank.
Glyphs are light with a dark shadow one pixel below, to read over any background.
Also writes snippets/hud/include/font.h, with each character's width.

Usage: python3 hud_font.py <assets/zelda-like/font.png> <snippets/hud folder>
"""
import sys

from PIL import Image

TRANSPARENT = (255, 0, 255)
LIGHT = (248, 240, 224)
SHADOW = (68, 57, 52)  # the pack's own glyph color

src = Image.open(sys.argv[1]).convert('RGBA')
snippet = sys.argv[2]

# Where each glyph is in font.png: (x, y, height). Letters and punctuation have
# descenders, so 12 rows; digits are packed 3 by 4 in 8x8 cells.
places = {}
for i in range(13):
    for row, first in ((0, 'A'), (16, 'N')):
        places[chr(ord(first) + i)] = (i * 16, row, 12)
        places[chr(ord(first.lower()) + i)] = (i * 16 + 8, row, 12)
for d in range(9):
    places[str(d)] = (216 + d % 3 * 8, d // 3 * 8, 8)
places['9'] = (224, 24, 8)
for i, c in enumerate('.,!¡?¿#_-▼:;\'"'):
    places[c] = (i * 8, 32, 12)

sheet = Image.new('RGB', (8, 16 * 94), TRANSPARENT)
widths = [4]  # the space
for n in range(94):
    c = chr(ord('!') + n)
    if c not in places:
        widths.append(0)
        continue
    x, y, height = places[c]
    glyph = src.crop((x, y, x + 8, y + height))
    columns = [gx for gx in range(8) for gy in range(height) if glyph.getpixel((gx, gy))[3]]
    left, right = min(columns), max(columns)
    for gy in range(height):
        for gx in range(left, right + 1):
            if glyph.getpixel((gx, gy))[3]:
                position = (gx - left, n * 16 + gy)
                sheet.putpixel(position, LIGHT)
                below = (position[0], position[1] + 1)
                if sheet.getpixel(below) == TRANSPARENT:
                    sheet.putpixel(below, SHADOW)
    widths.append(right - left + 1)
colors = [TRANSPARENT, LIGHT, SHADOW]
out = Image.new('P', sheet.size)
out.putdata([colors.index(p) for p in sheet.getdata()])
out.putpalette([c for color in colors + [(0, 0, 0)] * 13 for c in color])
out.save(f'{snippet}/graphics/font.bmp')
open(f'{snippet}/graphics/font.json', 'w').write('{\n    "type": "sprite",\n    "height": 16\n}\n')

rows = ',\n'.join('        ' + ', '.join(str(w) for w in widths[i:i + 16]) for i in range(0, len(widths), 16))
open(f'{snippet}/include/font.h', 'w').write(f'''#ifndef FONT_H
#define FONT_H

// Generated by snippets/tools/hud_font.py from the Zelda-like pack's font.png.

#include "bn_sprite_font.h"
#include "bn_sprite_items_font.h"

namespace hud
{{
    // Width in pixels of each character, from ' ' to '~'. 0 means the pack doesn't have it.
    constexpr int8_t font_widths[] = {{
{rows}
    }};

    // One pixel between characters.
    constexpr bn::sprite_font font(bn::sprite_items::font, bn::utf8_characters_map_ref(), font_widths, 1);
}}

#endif
''')
